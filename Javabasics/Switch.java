public class Switch {
    public static void main(String[] args) {
       
       int number = 2;

       switch (number) {
        
        case 3: System.out.println("mongo");
        break;

        case 1: System.out.println("orange");
        break;

        case 2: System.out.println("apple");
        break;

        default:System.out.println("wake up");

       }

    }
}